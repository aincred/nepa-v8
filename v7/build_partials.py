#!/usr/bin/env python3
"""
build_partials.py - rebuilds js/partials-bundle.js from the files in partials/.

WHEN TO RUN IT
  Every time you edit partials/header.html, partials/footer.html or partials/backtotop.html.

HOW
  python build_partials.py          (run it from the website folder)

WHY
  The bundle keeps a copy of each partial inside one small JavaScript file, so the header
  and footer appear instantly and work even when a page is opened by double-click.
  Do not edit js/partials-bundle.js by hand - it is overwritten by this script.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PART_DIR = os.path.join(ROOT, "partials")
OUT = os.path.join(ROOT, "js", "partials-bundle.js")

def build():
    files = sorted(f for f in os.listdir(PART_DIR) if f.endswith(".html"))
    if not files:
        sys.exit("ERROR: no .html files found in partials/")
    data = {}
    for f in files:
        with open(os.path.join(PART_DIR, f), encoding="utf-8", newline="") as fh:
            text = fh.read().replace("\r\n", "\n").replace("\r", "\n")
        if not text.strip():
            sys.exit("ERROR: partials/%s is empty - refusing to build a broken bundle" % f)
        data["partials/" + f] = text
    for needed in ("partials/header.html", "partials/footer.html"):
        if needed not in data:
            sys.exit("ERROR: %s is missing" % needed)
    # json.dumps output is valid JavaScript; escape </ so a partial can never close a <script> tag
    body = json.dumps(data, ensure_ascii=False, indent=1).replace("</", "<\\/")
    js = ("/* AUTO-GENERATED by build_partials.py - do not edit. "
          "Edit the files in partials/ instead, then run: python build_partials.py */\n"
          "window.NEPA_PARTIALS = " + body + ";\n")
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(js)
    os.replace(tmp, OUT)               # replace only after a complete write
    print("OK  js/partials-bundle.js rebuilt from: " + ", ".join(files))

if __name__ == "__main__":
    build()
